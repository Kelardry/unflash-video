//! The Huffman code books of Annex D.5 and a decoder for them.
//!
//! The books were extracted from the text of ETSI TS 102 114 V1.6.1 and,
//! separately, of V1.2.1 (2002), and the two compared: they agree except
//! for two misprints of V1.6.1, where V1.2.1 is taken: D65 lacks the
//! levels ±31 and ±32, and D129 prints level -37 as 37. Every book is
//! a complete prefix code over exactly its levels (the unit tests check
//! this, and a few entries as printed).

use crate::bits::Bits;

/// A code book as Annex D.5 prints it: (level, code length, code), the
/// code's bits most significant first.
pub type Book = &'static [(i8, u8, u16)];

/// A decoding tree for one book: node `i` has children `nodes[i]`, an
/// index of another node (the root, 0, is no one's child), or for a leaf
/// `LEAF - level`, which is negative.
pub struct Tree {
    nodes: Vec<[i16; 2]>,
}

/// Leaves hold `LEAF - level`: negative for every level (-64 to 64).
const LEAF: i16 = -1000;

impl Tree {
    pub fn new(book: Book) -> Tree {
        let mut nodes: Vec<[i16; 2]> = vec![[0, 0]];
        for &(level, len, code) in book {
            let mut node = 0usize;
            for k in (0..len).rev() {
                let bit = ((code >> k) & 1) as usize;
                if k == 0 {
                    nodes[node][bit] = LEAF - level as i16;
                } else {
                    if nodes[node][bit] == 0 {
                        // 0 is the root, never a child: free
                        nodes.push([0, 0]);
                        nodes[node][bit] = (nodes.len() - 1) as i16;
                    }
                    node = nodes[node][bit] as usize;
                }
            }
        }
        Tree { nodes }
    }

    /// Read one code. Every book is complete, so every bit string starts
    /// with a code; past the end of the data the zeros read decode too.
    #[inline]
    pub fn decode(&self, b: &mut Bits) -> i32 {
        let mut node = 0usize;
        loop {
            let next = self.nodes[node][b.read(1) as usize];
            if next < 0 {
                return (LEAF - next) as i32;
            }
            node = next as usize;
        }
    }
}

/// The books of the side information and the audio data, as trees.
pub struct Books {
    /// Quantization indexes for ABITS 1 to 10, by SEL (Table 5-26): A, B,
    /// C, ... (the block code and no-further-encoding selections have no
    /// book).
    pub audio: Vec<Vec<Tree>>,
    /// Scale factor differences (SA129 to SE129, SHUFF 0 to 4).
    pub scales: Vec<Tree>,
    /// Bit allocation indexes (A12 to E12, BHUFF 0 to 4).
    pub bit_alloc: Vec<Tree>,
    /// Transient modes (A4 to D4, THUFF 0 to 3).
    pub tmode: Vec<Tree>,
}

impl Books {
    pub fn new() -> Books {
        let trees = |books: &[Book]| books.iter().map(|&b| Tree::new(b)).collect::<Vec<_>>();
        Books {
            audio: AUDIO.iter().map(|books| trees(books)).collect(),
            scales: trees(&SCALES),
            bit_alloc: trees(&BIT_ALLOC),
            tmode: trees(&TMODE),
        }
    }
}

