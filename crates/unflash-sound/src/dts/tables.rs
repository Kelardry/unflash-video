#[cfg(test)]
mod tests {
    use super::*;

    /// The scale factor tables are 2 dB plus 2.2 dB (6-bit) or 1.1 dB
    /// (7-bit) per step, rounded; their largest entries as printed.
    #[test]
    fn scale_factor_tables_follow_their_steps() {
        for (i, &v) in RMS6.iter().enumerate() {
            let exact = 10f64.powf((2.2 * i as f64 + 2.0) / 20.0);
            assert!((v as f64 - exact).abs() <= 0.5, "6-bit {i}: {v} {exact}");
        }
        for (i, &v) in RMS7.iter().enumerate() {
            let exact = 10f64.powf((1.1 * i as f64 + 2.0) / 20.0);
            assert!((v as f64 - exact).abs() <= 0.5, "7-bit {i}: {v} {exact}");
        }
        assert_eq!((RMS6[62], RMS7[124], RMS7[64]), (8317638, 8317638, 4169));
    }

    #[test]
    fn step_sizes_as_printed() {
        // the nominal step sizes of D.2.1 times 2^22
        for (abits, nominal) in [(1, 1.6), (2, 1.0), (5, 0.5), (8, 0.19), (11, 0.035), (15, 0.004), (19, 0.00045), (26, 0.000005)] {
            let v = STEP_LOSSY[abits] as f64 / (1 << 22) as f64;
            assert!((v - nominal).abs() < nominal * 0.01, "{abits}: {v}");
        }
        // the lossless ones halve with each bit from ABITS 8
        for abits in 9..27 {
            let ratio = STEP_LOSSLESS[abits - 1] as f64 / STEP_LOSSLESS[abits] as f64;
            assert!((ratio - 2.0).abs() < 0.02, "{abits}");
        }
        assert_eq!((STEP_LOSSLESS[1], STEP_LOSSLESS[26]), (1 << 22, 1));
    }

    /// Joint intensity scales are 0.5 dB steps around 0 dB at index 64 (the
    /// lower half as printed is off the formula by up to 0.13 %).
    #[test]
    fn joint_scales_are_half_decibel_steps() {
        for (i, &v) in JOINT_SCALES.iter().enumerate() {
            let exact = 10f64.powf((i as f64 - 64.0) * 0.5 / 20.0);
            assert!((v as f64 - exact).abs() < exact * 1.3e-3, "{i}: {v}");
        }
        assert_eq!(JOINT_SCALES[64], 1.0);
    }

    /// DmixTable is 2^15 times -60 to -30 dB in 0.5 dB steps, to -15 dB
    /// in 0.25 dB steps, to 0 dB in 0.125 dB steps, rounded (-3 dB is
    /// 2^15 / sqrt 2).
    #[test]
    fn downmix_table_follows_its_steps() {
        for (i, &v) in DMIX_TABLE.iter().enumerate() {
            let db = if i <= 60 {
                -60.0 + 0.5 * i as f64
            } else if i <= 120 {
                -30.0 + 0.25 * (i - 60) as f64
            } else {
                -15.0 + 0.125 * (i - 120) as f64
            };
            let exact = if i == 216 { 32768.0 * std::f64::consts::FRAC_1_SQRT_2 } else { 32768.0 * 10f64.powf(db / 20.0) };
            assert!((v as f64 - exact).abs() <= 0.5, "{i}: {v} {exact}");
        }
    }

    #[test]
    fn range_gains_as_printed() {
        // D.4's multipliers
        for (i, m) in [(0u8, 0.0259), (47, 0.1000), (127, 1.0), (200, 8.1752), (255, 39.8107)] {
            assert!((range_gain(i) - m).abs() < m * 2e-3, "{i}");
        }
    }
}
