/// The gain of a dynamic range coefficient RANGE (D.4): 0.25 dB steps,
/// -31.75 dB at 0, 0 dB at 127, +32 dB at 255.
pub fn range_gain(range: u8) -> f64 {
    10f64.powf((range as f64 - 127.0) * 0.25 / 20.0)
}

